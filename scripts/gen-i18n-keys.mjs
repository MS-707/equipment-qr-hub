#!/usr/bin/env node
/**
 * Generates the MessageKey union from en.json so every t() key is
 * tsc-checked (ES-1). Run after editing catalogs:
 *   node scripts/gen-i18n-keys.mjs
 * A vitest freshness check fails if this file is stale.
 *
 * Plural groups (an object whose keys are only Intl.PluralRules categories,
 * including 'other') emit the PARENT key — callers write
 * t('sync.recordsSynced', { count }) and t() selects the variant.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const PLURAL_CATEGORIES = new Set(['zero', 'one', 'two', 'few', 'many', 'other'])

function isPluralGroup(node) {
  if (!node || typeof node !== 'object') return false
  const keys = Object.keys(node)
  return (
    keys.length > 0 &&
    keys.includes('other') &&
    keys.every((k) => PLURAL_CATEGORIES.has(k) && typeof node[k] === 'string')
  )
}

function collectMessageKeys(tree) {
  const keys = []
  function walk(node, prefix) {
    for (const [k, v] of Object.entries(node)) {
      const key = prefix ? `${prefix}.${k}` : k
      if (v && typeof v === 'object') {
        if (isPluralGroup(v)) keys.push(key)
        else walk(v, key)
      } else {
        keys.push(key)
      }
    }
  }
  walk(tree, '')
  return keys
}

function renderKeyUnion(keys) {
  return `// AUTO-GENERATED by scripts/gen-i18n-keys.mjs — do not edit by hand.
// Regenerate after catalog changes; the i18n-catalog vitest pins freshness.
export type MessageKey =
${keys.map((k) => `  | '${k}'`).join('\n')}
`
}

const en = JSON.parse(readFileSync('src/messages/en.json', 'utf8'))
const keys = collectMessageKeys(en)
writeFileSync('src/lib/i18n-keys.d.ts', renderKeyUnion(keys))
console.log(`generated ${keys.length} keys`)

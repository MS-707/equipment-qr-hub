#!/usr/bin/env node
/**
 * Generates the MessageKey union from en.json so every t() key is
 * tsc-checked (ES-1). Run after editing catalogs:
 *   node scripts/gen-i18n-keys.mjs
 * A vitest freshness check fails if this file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const en = JSON.parse(readFileSync('src/messages/en.json', 'utf8'))
const keys = []
function walk(node, prefix) {
  for (const [k, v] of Object.entries(node)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (v && typeof v === 'object') walk(v, key)
    else keys.push(key)
  }
}
walk(en, '')
const body = `// AUTO-GENERATED by scripts/gen-i18n-keys.mjs — do not edit by hand.
// Regenerate after catalog changes; the i18n-catalog vitest pins freshness.
export type MessageKey =
${keys.map((k) => `  | '${k}'`).join('\n')}
`
writeFileSync('src/lib/i18n-keys.d.ts', body)
console.log(`generated ${keys.length} keys`)
